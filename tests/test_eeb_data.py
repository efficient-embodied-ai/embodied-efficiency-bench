# CLI (Gate 3: documented commands executed verbatim, both flag orders)
# --------------------------------------------------------------------------------------------
def _run_cli(argv):
  import argparse

  parser = argparse.ArgumentParser(prog="eeb")
  sub = parser.add_subparsers(dest="subcommand", required=True)
  data_cli.register_cli(sub)                       # exactly how WS-A's eeb/cli.py wires it
  args = parser.parse_args(argv)
  return args.func(args)


def test_cli_register_and_verbatim_commands(tmp_path, mini_v3, capsys):
  src = str(mini_v3.root)
  out1, out2 = tmp_path / "o1", tmp_path / "o2"
  assert _run_cli(["data", "pack-traces", src, "--out", str(out1), "--max-episodes", "1", "--split", "public"]) == 0
  assert _run_cli(["data", "pack-traces", "--split", "public", "--max-episodes", "1", "--out", str(out2), src]) == 0   # flag order swapped
  assert (out1 / "traces" / "public" / "episode_0000.npz").exists() and (out2 / "traces" / "public" / "manifest.json").exists()
  assert _run_cli(["data", "inspect", str(out1)]) == 0
  assert "manifest verification OK" in capsys.readouterr().out
  assert _run_cli(["data", "inspect", "--deep", str(out1)]) == 0
  capsys.readouterr()
  assert _run_cli(["data", "inspect", src]) == 0                                     # LeRobot root summary
  info = json.loads(capsys.readouterr().out)
  assert info["layout"] == "v3" and info["episodes_with_local_data"] == 2
  assert _run_cli(["data", "perturb", str(out1), "--out", str(tmp_path / "p1"), "--split", "public", "--seed", "3"]) == 0
  assert _run_cli(["data", "perturb", "--seed", "3", "--split", "public", "--out", str(tmp_path / "p2"), str(out1)]) == 0
  assert (tmp_path / "p1" / "perturbed" / "public" / "perturbation_manifest.json").exists()
  assert json.loads((tmp_path / "p1" / "perturbed" / "public" / "perturbation_manifest.json").read_text())["sha256"] == json.loads((tmp_path / "p2" / "perturbed" / "public" / "perturbation_manifest.json").read_text())["sha256"]
  assert _run_cli(["data", "inspect", str(tmp_path / "p1" / "perturbed" / "public")]) == 0
  capsys.readouterr()
  assert _run_cli(["data", "download", "ignored/id", "--plan-only", src, "--episodes", "1"]) == 0
  plan = json.loads(capsys.readouterr().out)
  assert plan["data_files"] == ["data/chunk-000/file-000.parquet"]
  # error paths return non-zero with a message instead of a traceback
  assert _run_cli(["data", "pack-traces", str(tmp_path / "nope"), "--out", str(tmp_path / "o3")]) == 2
  assert "ERROR" in capsys.readouterr().out
  assert _run_cli(["data", "pack-traces", src, "--out", str(tmp_path / "o4"), "--fps", "3"]) == 2
  # standalone module entry point works in a fresh interpreter (no umbrella CLI needed)
  proc = subprocess.run([sys.executable, "-m", "eeb.data", "inspect", str(out1)], cwd=str(REPO_ROOT), capture_output=True, text=True, timeout=120)
  assert proc.returncode == 0, proc.stderr
  assert "manifest verification OK" in proc.stdout
  proc2 = subprocess.run([sys.executable, "tests/fixtures/make_mini_lerobot.py", "--out", str(tmp_path / "cli_fixture"), "--data-format", "fallback"], cwd=str(REPO_ROOT), capture_output=True, text=True, timeout=120)
  assert proc2.returncode == 0 and "SYNTHETIC FIXTURE" in proc2.stdout, proc2.stderr
