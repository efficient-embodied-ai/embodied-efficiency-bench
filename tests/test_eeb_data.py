def test_pack_writes_manifest_and_sha256_verifies_then_tamper_fails(packed):
  traces = packed.traces_dir
  assert (traces / "manifest.json").exists()
  results = pk.verify_traces(packed.out_dir)
  assert results and all(v.ok for v in results.values()), {k: v.summary() for k, v in results.items()}
  deep = pk.verify_traces(packed.out_dir, deep=True)
  assert all(v.ok for v in deep.values())
  split, man = next(iter(packed.manifests.items()))
  d = man.to_dict()
  assert d["schema_version"] == sc.SCHEMA_VERSION and d["episode_count"] == man.episode_count
  assert set(d["sha256"]) == {e.file for e in man.episodes}
  assert d["license"] == "" or isinstance(d["license"], str)
  assert d["cameras"] == ["image", "wrist_image"] and d["fps"] == FPS and d["native_fps"] == FPS
  # tamper one byte -> verification must fail for exactly that file
  target = traces / split / man.episodes[0].file
  original = target.read_bytes()
  try:
    target.write_bytes(original[:-1] + bytes([original[-1] ^ 0xFF]))
    bad = pk.verify_traces(packed.out_dir)[split]
    assert not bad.ok and any(man.episodes[0].file in m for m in bad.mismatches)
  finally:
    target.write_bytes(original)
  assert pk.verify_traces(packed.out_dir)[split].ok


def test_pack_preserves_temporal_order_and_constant_instruction(packed, mini_v3):
  by_idx = {e.source_episode_index: (split, e) for split, man in packed.manifests.items() for e in man.episodes}
  assert sorted(by_idx) == [0, 1] and packed.episode_count == 2
  for ep in mini_v3.episodes:
    split, me = by_idx[ep.episode_index]
    tr = sc.EmbodiedXTrace.from_npz(packed.traces_dir / split / me.file)
    assert me.file == f"episode_{ep.episode_index:04d}.npz"
    assert np.all(np.diff(tr.t_ns) > 0) and tr.t_ns.tolist() == [int(round(i * 1e9 / FPS)) for i in range(N_STEPS)]
    assert tr.step.tolist() == list(range(N_STEPS))
    assert tr.instruction == ep.task == me.instruction
    assert tr.split == split in sc.SPLITS
    assert tr.episode_id == me.episode_id == sc.make_episode_id(mini_v3.root.name, ep.episode_index)
    assert np.array_equal(tr.images["wrist_image"], ep.images["wrist_image"])
    assert np.array_equal(tr.action, ep.action)
    assert tr.content_sha256() == me.content_sha256
  assert pk.load_split(packed.out_dir, split)[0].split == split


