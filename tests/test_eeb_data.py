def test_golden_store_load_verify_and_tamper(tmp_path, packed):
  split, man = next(iter(packed.manifests.items()))
  me = man.episodes[0]
  tr = sc.EmbodiedXTrace.from_npz(packed.traces_dir / split / me.file)
  rng = np.random.default_rng(0)
  actions = rng.normal(size=(len(tr), 8, 7)).astype(np.float32)   # [T, H=8, A=7] chunks
  g = gd.GoldenEpisode(model_id="pi05-3b", split=split, episode_id=tr.episode_id, source_episode_index=me.source_episode_index,
                       actions=actions, step=tr.step, t_ns=tr.t_ns, trace_content_sha256=tr.content_sha256(), extra={"checkpoint": "lerobot/pi05_base"})
  path = gd.save_golden(tmp_path, g)
  assert path == tmp_path / "golden" / "pi05-3b" / split / f"episode_{me.source_episode_index:04d}.npz"
  loaded = gd.load_golden(tmp_path, "pi05-3b", split, me.source_episode_index)
  assert np.array_equal(loaded.actions, actions) and loaded.horizon == 8 and loaded.action_dim == 7
  assert loaded.trace_content_sha256 == tr.content_sha256() and loaded.extra["checkpoint"] == "lerobot/pi05_base"
  assert np.array_equal(loaded.step, tr.step) and np.array_equal(loaded.t_ns, tr.t_ns)
  rep = gd.verify_golden(tmp_path, "pi05-3b", split)
  assert rep["ok"] and rep["checked"] == 1 and gd.list_golden(tmp_path, "pi05-3b", split) == [path.name]
  # 2-D actions are promoted to H=1; wrong lengths / bad hash rejected
  g2 = gd.GoldenEpisode("m", split, tr.episode_id, 1, actions[:, 0, :], tr.step, tr.t_ns, tr.content_sha256())
  assert g2.horizon == 1
  with pytest.raises(ValueError):
    gd.GoldenEpisode("m", split, tr.episode_id, 1, actions, tr.step[:-1], tr.t_ns, tr.content_sha256())
  with pytest.raises(ValueError):
    gd.GoldenEpisode("m", split, tr.episode_id, 1, actions, tr.step, tr.t_ns, "deadbeef")
  # Gate-A math helpers
  assert gd.action_cosine_similarity(actions, actions) == pytest.approx(1.0)
  assert gd.action_cosine_similarity(actions, -actions) == pytest.approx(-1.0)
  assert gd.action_l2_error(actions, actions)["max_abs"] == 0.0
  assert gd.action_cosine_similarity(actions, actions + np.float32(1e-3)) > 0.995
  # tamper -> load_golden refuses
  raw = path.read_bytes()
  path.write_bytes(raw[:-1] + bytes([raw[-1] ^ 0xFF]))
  with pytest.raises(ValueError, match="sha256"):
    gd.load_golden(tmp_path, "pi05-3b", split, me.source_episode_index)
  assert not gd.verify_golden(tmp_path, "pi05-3b", split)["ok"]


