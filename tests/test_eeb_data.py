def _assert_roundtrip(ds, lr: ll.LeRobotDataset, lossless: bool = True):
  assert [e.episode_index for e in lr.episodes] == [0, 1]
  for e in ds.episodes:
    tr = lr.load_episode(e.episode_index)
    assert len(tr) == N_STEPS
    assert tr.cameras == tuple(sorted(ds.cameras))
    assert tr.instruction == e.task
    assert tr.step.tolist() == list(range(N_STEPS))
    assert tr.t_ns.tolist() == [int(round(i * 1e9 / FPS)) for i in range(N_STEPS)]
    assert np.array_equal(tr.proprio, e.state) and tr.proprio.dtype == np.float32
    assert np.array_equal(tr.action, e.action) and tr.action.dtype == np.float32
    for cam in ds.cameras:
      got, exp = tr.images[cam], e.images[cam]
      assert got.dtype == np.uint8 and got.shape == exp.shape == (N_STEPS, 64, 64, 3)
      if lossless:
        assert np.array_equal(got, exp), f"{cam}: decoded frames differ from ground truth"
      else:  # lossy codec: every decoded frame must be closer to its own ground truth than to its neighbours
        for i in range(N_STEPS):
          own = np.abs(got[i].astype(int) - exp[i].astype(int)).mean()
          nb = min(np.abs(got[i].astype(int) - exp[j].astype(int)).mean() for j in (i - 1, i + 1) if 0 <= j < N_STEPS)
          assert own < nb, f"{cam} frame {i}: nearest-neighbour frame alignment broken ({own:.2f} vs {nb:.2f})"
          assert own < 8.0, f"{cam} frame {i}: lossy error too high ({own:.2f})"
    tr.validate()


