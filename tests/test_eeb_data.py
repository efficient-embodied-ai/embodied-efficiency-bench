def test_perturb_determinism_linf_bound_and_negative_controls(mini_v3):
  tr = ll.LeRobotDataset(mini_v3.root).load_episode(0)
  step = tr[4]
  cfg = pb.PerturbationConfig(seed=123, eps_linf=1e-3)
  p1, p2 = pb.perturb_step(step, cfg), pb.perturb_step(step, cfg)
  for cam in tr.cameras:
    assert p1.images[cam].dtype == np.float32 and np.array_equal(p1.images[cam], p2.images[cam])   # deterministic
    ref = step.images[cam].astype(np.float32) / np.float32(255.0)
    d = np.max(np.abs(p1.images[cam] - ref))
    assert d <= 1e-3 * (1 + 1e-4) and d >= 1e-3 * (1 - 1e-3), d                                     # ‖δ‖∞ == eps (positive)
    assert p1.images[cam].min() >= 0.0 and p1.images[cam].max() <= 1.0
  assert np.array_equal(p1.proprio, p2.proprio)
  dp = np.max(np.abs(p1.proprio - step.proprio))
  assert dp <= 1e-3 * (1 + 1e-4) and dp >= 1e-3 * (1 - 1e-3), dp
  # negative controls: different seed / different step / different eps all change the perturbation
  q = pb.perturb_step(step, pb.PerturbationConfig(seed=124, eps_linf=1e-3))
  assert not np.array_equal(q.images["image"], p1.images["image"]) and not np.array_equal(q.proprio, p1.proprio)
  other = pb.perturb_step(tr[5], cfg)
  d_self = p1.images["image"] - step.images["image"].astype(np.float32) / 255.0
  d_other = other.images["image"] - tr[5].images["image"].astype(np.float32) / 255.0
  assert not np.array_equal(d_self, d_other)
  big = pb.perturb_step(step, pb.PerturbationConfig(seed=123, eps_linf=2e-3))
  assert np.max(np.abs(big.proprio - step.proprio)) == pytest.approx(2e-3, rel=1e-3)
  assert pb.derive_step_seed(1, "a", 0) != pb.derive_step_seed(1, "a", 1) != pb.derive_step_seed(2, "a", 1)
  with pytest.raises(ValueError, match="1/255"):
    pb.PerturbationConfig(eps_linf=5e-3)
  # uint8 LSB mode: stays uint8, effective ‖δ‖∞ = 1/255, roughly lsb_fraction of pixels change
  u8 = pb.perturb_step(step, pb.PerturbationConfig(seed=5, image_space="uint8_lsb", lsb_fraction=0.05))
  img = u8.images["image"]
  assert img.dtype == np.uint8
  diff = np.abs(img.astype(int) - step.images["image"].astype(int))
  assert diff.max() == 1 and 0.02 < (diff > 0).mean() < 0.08
  assert pb.PerturbationConfig(image_space="uint8_lsb").eps_linf_effective == pytest.approx(1 / 255)
  # jitter / brightness probes are flagged as non-cache probes and exceed eps
  jit = pb.PerturbationConfig(seed=9, camera_jitter_px=3, brightness_jitter=0.1)
  assert not jit.g4_cache_probe_valid and pb.PerturbationConfig().g4_cache_probe_valid
  pj = pb.perturb_step(step, jit)
  assert pj.delta_linf["image"] > 1e-3 and "shift_px" in pj.jitter["image"]
  img0 = step.images["image"]
  sh = pb.shift_image(img0, 2, -1)                                            # dx=+2 (content moves right), dy=-1 (content moves up)
  assert sh.shape == img0.shape and np.array_equal(sh[:-1, 2:], img0[1:, :-2])
  assert np.array_equal(sh[:, 0], sh[:, 1]) and np.array_equal(sh[-1], sh[-2])  # edge replication, no wrap-around
  assert pb.shift_image(img0, 0, 0) is img0


def test_perturb_split_materialisation_manifest_and_tamper(tmp_path, packed):
  split = next(iter(packed.manifests))
  cfg = pb.PerturbationConfig(seed=42)
  mpath = pb.write_perturbed_split(packed.out_dir, tmp_path / "pert", cfg, split=split)
  assert mpath.name == "perturbation_manifest.json"
  man = json.loads(mpath.read_text())
  assert man["kind"] == "g4_perturbation" and man["config"]["seed"] == 42 and man["config"]["eps_linf"] == 1e-3
  assert man["config"]["g4_cache_probe_valid"] is True and man["episode_count"] == packed.manifests[split].episode_count
  assert man["source_traces_manifest_sha256"] == sc.sha256_file(packed.traces_dir / split / "manifest.json")
  ok, problems = pb.verify_perturbation_manifest(mpath)
  assert ok, problems
  ep = man["episodes"][0]
  assert ep["max_delta_linf"]["proprio"] == pytest.approx(1e-3, rel=1e-3) and ep["max_delta_linf"]["image"] == pytest.approx(1e-3, rel=1e-3)
  pt = pb.PerturbedTrace.from_npz(mpath.parent / ep["file"])
  assert pt.config == cfg and pt.source_content_sha256 == ep["source_content_sha256"] and pt.content_sha256() == ep["content_sha256"]
  # re-materialising with the same seed is byte-identical; a different seed is not
  m2 = pb.write_perturbed_split(packed.out_dir, tmp_path / "pert2", cfg, split=split)
  assert json.loads(m2.read_text())["sha256"] == man["sha256"]
  m3 = pb.write_perturbed_split(packed.out_dir, tmp_path / "pert3", pb.PerturbationConfig(seed=43), split=split)
  assert json.loads(m3.read_text())["sha256"] != man["sha256"]
  f = mpath.parent / ep["file"]
  raw = f.read_bytes()
  f.write_bytes(raw[:-1] + bytes([raw[-1] ^ 0xFF]))  # flip the last byte (zip EOCD comment length) -> sha256 changes
  ok2, problems2 = pb.verify_perturbation_manifest(mpath)
  assert not ok2 and problems2


