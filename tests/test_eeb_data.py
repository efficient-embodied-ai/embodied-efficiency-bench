def test_split_assignment_determinism_and_negative_control(tmp_path, mini_v3):
  ids = [sc.make_episode_id("org/name", i) for i in range(400)]
  a = [sc.assign_split(i, seed=1, hidden_fraction=0.5) for i in ids]
  assert a == [sc.assign_split(i, seed=1, hidden_fraction=0.5) for i in ids]  # same seed -> identical
  b = [sc.assign_split(i, seed=2, hidden_fraction=0.5) for i in ids]
  assert a != b                                                               # different seed -> different (negative control)
  frac = a.count("hidden") / len(a)
  assert 0.35 < frac < 0.65, frac                                            # both labels occur at the requested rate
  assert all(s == "public" for s in (sc.assign_split(i, hidden_fraction=0.0) for i in ids))
  assert all(s == "hidden" for s in (sc.assign_split(i, hidden_fraction=1.0) for i in ids))
  with pytest.raises(ValueError):
    sc.assign_split("x", hidden_fraction=1.5)
  # packer honours the policy and records it
  auto = pk.pack_traces(mini_v3.root, tmp_path / "auto", seed=7, hidden_fraction=0.5)
  for split, man in auto.manifests.items():
    assert man.split_policy["seed"] == 7 and man.split_policy["hidden_fraction"] == 0.5
    for e in man.episodes:
      assert sc.assign_split(e.episode_id, seed=7, hidden_fraction=0.5) == split
  forced = pk.pack_traces(mini_v3.root, tmp_path / "forced", split="public")
  assert list(forced.manifests) == ["public"] and forced.manifests["public"].episode_count == 2
  assert forced.manifests["public"].split_policy["forced_split"] == "public"
  with pytest.raises(ValueError, match="split"):
    pk.pack_traces(mini_v3.root, tmp_path / "bad", split="train")


